// IDs are stable references, shared by every template and workout.
// Group defaults describe the movement family; individual rows can override them.
type Row = [id: string, name: string, equipment: Equipment[], overrides?: Partial<ExerciseSeed>]
function group(primaryMuscle: TargetMuscle, muscle: MuscleGroup, movementPattern: MovementPattern, secondaryMuscles: TargetMuscle[], rows: Row[]): ExerciseSeed[] {
  return rows.map(([id,name,equipment,overrides]) => ({id,name,equipment,primaryMuscle,muscle,movementPattern,secondaryMuscles,unit:'reps',...overrides}))
}
